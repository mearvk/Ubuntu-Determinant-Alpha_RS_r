#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

CC="${CC:-gcc}"
CXX="${CXX:-g++}"
CFLAGS="${CFLAGS:--O2 -Wall -Wextra -std=c11}"
CXXFLAGS="${CXXFLAGS:--O2 -Wall -Wextra -std=c++17}"

mkdir -p build/bin build/lib

if [[ ! -f xgcc-generations.c ]]; then
  echo "Missing xgcc-generations.c" >&2
  exit 1
fi

$CC $CFLAGS -o build/bin/xgcc-generations xgcc-generations.c

# The C++ interface is provided as a stable header. A tiny ABI smoke binary
# verifies that the header remains valid for C++ consumers.
cat > build/xgcc-header-smoke.cpp <<'CPP'
#include "../xgcc.hpp"
int main() { return xgcc::build_info().name == nullptr; }
CPP
$CXX $CXXFLAGS -I. -o build/bin/xgcc-header-smoke build/xgcc-header-smoke.cpp
rm -f build/xgcc-header-smoke.cpp

cp build/bin/xgcc-generations build/bin/xgcc-generations-linux-x86_64

cat > build/MANIFEST.txt <<EOF
XGCC generated binaries
Generated by: build-binaries.sh
Compiler C:   $CC
Compiler C++: $CXX
CFLAGS:       $CFLAGS
CXXFLAGS:     $CXXFLAGS

Artifacts:
  build/bin/xgcc-generations
  build/bin/xgcc-generations-linux-x86_64
  build/bin/xgcc-header-smoke

These are locally generated build artifacts. Rebuild rather than treating
binary files as authoritative source.
EOF

echo "XGCC binaries generated under $ROOT/build/bin"
